#!/usr/bin/env python3
"""
WDS — build the search-friendly static pages from a database export.

    python3 tools/seo/build.py <export.json|export.csv> [--no-render]

Input: the result of tools/seo/export.sql (run in the Supabase SQL Editor and
downloaded as CSV, or saved as JSON). Output, written into the repo:

    events/<slug>/index.html      one page per finished event (results)
    fighters/<slug>/index.html    one page per fighter (profile + fight history)
    fighters/index.html           A-Z list of all fighters
    <old WordPress path>/index.html  redirects from the old site's results URLs
    js/wds-static-urls.js         map used by the live scripts to link to these pages
    sitemap.xml

Then tools/seo/prerender.js (Node + Playwright) runs the site's own scripts on
every page against the export and saves the rendered content into the HTML,
so search engines see the full results without running JavaScript. Visitors
still get live data: the same scripts refresh the page from the database.
This tool only reads the export; it never writes to the database.
"""
import csv, datetime as dt, html, json, os, re, subprocess, sys, unicodedata

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SITE = 'https://wdsmma.com'
ORG = 'Warriors Dream Series'
OG_DEFAULT = SITE + '/assets/images/og/wds-og-default.jpg'
MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']
RESULT_LABEL = {
    'DECISION_UNANIMOUS': 'unanimous decision', 'DECISION_SPLIT': 'split decision', 'DECISION_MAJORITY': 'majority decision',
    'KO_HEAD': 'KO', 'KO_BODY': 'KO', 'TKO': 'TKO', 'SUBMISSION': 'submission', 'RNC': 'submission',
    'DOCTOR_STOPPAGE': 'TKO (doctor stoppage)', 'CORNER_STOPPAGE': 'TKO (corner stoppage)', 'DQ': 'disqualification',
}
# Results pages of the old WordPress site -> event slug (from events.results_url)
STATIC_FILES_NOTE = '<!-- Generated by tools/seo/build.py from the WDS database. Edit the template, not this file. -->'


def load_export(path):
    raw = open(path, encoding='utf-8-sig').read()
    if path.lower().endswith('.csv'):
        csv.field_size_limit(1 << 30)
        rows = list(csv.reader(raw.splitlines(True)))
        cell = rows[1][0] if rows and rows[0] and rows[0][0].strip() == 'wds_export' else rows[0][0]
        return json.loads(cell)
    data = json.loads(raw)
    if isinstance(data, list):           # [{"wds_export": {...}}]
        data = data[0]
    return data.get('wds_export', data)


def slugify(s):
    s = unicodedata.normalize('NFKD', s or '').encode('ascii', 'ignore').decode()
    return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-') or 'fighter'


def e(s):
    return html.escape(str(s if s is not None else ''), quote=True)


def fmt_date(iso, long=False):
    if not iso:
        return ''
    y, m, d = map(int, iso[:10].split('-'))
    return '%d %s %d' % (d, (dt.date(y, m, d).strftime('%B') if long else MONTHS[m - 1]), y)


def absolute(url):
    if not url:
        return ''
    url = url.replace('http://', 'https://')
    url = re.sub(r'^https://candies-studios\.github\.io/warriors-dream-series/', SITE + '/', url)
    if url.startswith('http'):
        return url
    return SITE + '/' + url.lstrip('/')


def clip(text, n=158):
    text = re.sub(r'\s+', ' ', text).strip()
    if len(text) <= n:
        return text
    cut = text[:n - 1]
    cut = cut[:cut.rfind(' ')] if ' ' in cut else cut
    return cut.rstrip(' ,.;·—-') + '…'


# --------------------------------------------------------------------- data
class Data:
    def __init__(self, x):
        self.exported_at = x.get('exported_at', '')
        self.events = [ev for ev in x['events'] if ev.get('status') != 'draft']
        self.by_event_id = {ev['id']: ev for ev in self.events}
        self.card = [b for b in x['bout_card'] if b['event_id'] in self.by_event_id]
        self.fighters = {f['id']: f for f in x['fighters']}
        self.points = x.get('bout_points') or []
        # finished, listed events get a static results page
        self.static_events = [ev for ev in self.events
                              if ev.get('status') == 'completed' and ev.get('is_listed', True)
                              and any(b['event_id'] == ev['id'] for b in self.card)]
        self.static_events.sort(key=lambda ev: ev.get('event_date') or '', reverse=True)
        # every fighter on a public fight card gets a profile page
        ids = set()
        for b in self.card:
            ids.update(i for i in (b['blue_fighter_id'], b['red_fighter_id']) if i)
        people = sorted((self.fighters[i] for i in ids if i in self.fighters),
                        key=lambda f: (f.get('public_id') or '', f['id']))
        self.fighter_slug, used = {}, set()
        for f in people:
            base = slugify(f['name'])
            slug = base
            n = 2
            while slug in used:
                slug = '%s-%d' % (base, n)
                n += 1
            used.add(slug)
            self.fighter_slug[f['id']] = slug
        self.static_fighters = sorted(people, key=lambda f: f['name'].lower())

    def bouts_of_event(self, ev):
        return sorted((b for b in self.card if b['event_id'] == ev['id']), key=lambda b: b['bout_number'])

    def fights_of(self, f):
        rows = []
        for b in self.card:
            if f['id'] not in (b['blue_fighter_id'], b['red_fighter_id']):
                continue
            ev = self.by_event_id[b['event_id']]
            red = b['red_fighter_id'] == f['id']
            final = b.get('result_status') == 'final'
            out = 'up'
            if final:
                out = 'NC' if b.get('result_type') == 'NO_CONTEST' else 'W' if b.get('winner_id') == f['id'] else 'L' if b.get('winner_id') else 'D'
            rows.append(dict(bout=b, event=ev, date=ev.get('event_date') or '', final=final, outcome=out,
                             pro=b.get('bout_type') == 'PROFESSIONAL',
                             opponent=(b['blue_name'] if red else b['red_name']) or 'TBA',
                             opponent_id=b['blue_fighter_id'] if red else b['red_fighter_id']))
        rows.sort(key=lambda r: r['date'], reverse=True)
        return rows


def record(rows):
    r = {'W': 0, 'L': 0, 'D': 0, 'NC': 0}
    for x in rows:
        if x['final'] and x['outcome'] in r:
            r[x['outcome']] += 1
    return '%d-%d-%d' % (r['W'], r['L'], r['D']) + (' (%d NC)' % r['NC'] if r['NC'] else '')


def method(b):
    t = b.get('result_type') or ''
    m = RESULT_LABEL.get(t, t.replace('_', ' ').lower())
    if b.get('end_round') and not re.match(r'DECISION|DRAW', t):
        m += ' in round %d' % b['end_round']
    return m


# --------------------------------------------------------------------- html helpers
def depth_paths(s, depth):
    """Rewrite a /pages template's relative URLs for a page `depth` folders below the root."""
    up = '../' * depth
    s = re.sub(r'((?:href|src)=")\.\./', r'\g<1>' + up, s)
    s = re.sub(r'(href=")((?:events|rankings|about|contact|media-room|blog|event|fighter)\.html)', r'\g<1>' + up + r'pages/\2', s)
    s = s.replace("url('../", "url('" + up)
    return s


def set_head(s, title, desc, canonical, image, og_type='website', ld=(), robots=None):
    head, body = s.split('</head>', 1)
    head = re.sub(r'<title>.*?</title>', '<title>' + e(title) + '</title>', head, count=1, flags=re.S)
    head = re.sub(r'<meta name="description" content="[^"]*">', '<meta name="description" content="' + e(desc) + '">', head, count=1)
    og_title = re.sub(r'\s*\|\s*(WDS MMA|Warriors Dream Series)$', '', title)
    lines = []
    if robots:
        lines.append('<meta name="robots" content="%s">' % robots)
    lines += ['<link rel="canonical" href="%s">' % canonical,
              '<meta property="og:type" content="%s">' % og_type,
              '<meta property="og:site_name" content="%s">' % ORG,
              '<meta property="og:locale" content="en_IN">',
              '<meta property="og:title" content="%s">' % e(og_title),
              '<meta property="og:description" content="%s">' % e(desc),
              '<meta property="og:url" content="%s">' % canonical,
              '<meta property="og:image" content="%s">' % e(image or OG_DEFAULT)]
    if not image or image == OG_DEFAULT:
        lines += ['<meta property="og:image:width" content="1200">', '<meta property="og:image:height" content="630">']
    lines += ['<meta property="og:image:alt" content="%s">' % e(og_title),
              '<meta name="twitter:card" content="summary_large_image">',
              '<meta name="theme-color" content="#050505">']
    head = re.sub(r'<!-- SEO -->.*?<!-- /SEO -->', '<!-- SEO -->\n' + '\n'.join(lines) + '\n<!-- /SEO -->', head, count=1, flags=re.S)
    for block in ld:
        head = head.rstrip('\n') + '\n<script type="application/ld+json">\n' + json.dumps(block, ensure_ascii=False, indent=2) + '\n</script>\n'
    return head + '</head>' + body


def crumbs(*items):
    return {"@context": "https://schema.org", "@type": "BreadcrumbList",
            "itemListElement": [{"@type": "ListItem", "position": i + 1, "name": n, "item": SITE + u}
                                for i, (n, u) in enumerate(items)]}


def mark(s, start_pat, end_pat, name):
    """Wrap the region from start_pat up to and including end_pat in <!--PRE:name--> markers."""
    if '<!--PRE:%s-->' % name in s:
        return s
    i = s.index(start_pat)
    j = s.index(end_pat, i) + len(end_pat)
    return s[:i] + '<!--PRE:%s-->' % name + s[i:j] + '<!--/PRE:%s-->' % name + s[j:]


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text)


