def old_site_redirects(D):
    out = []
    for ev in D.static_events:
        u = ev.get('results_url') or ''
        m = re.match(r'https?://(?:www\.)?warriors?dreams?series\.com/([^?#]+?)/?$', u)
        if not m:
            continue
        path = m.group(1).strip('/')
        target = '/events/%s/' % ev['slug']
        page = '''<!DOCTYPE html>
<html lang="en-IN">
<head>
<meta charset="UTF-8">
<title>%s Results — Warriors Dream Series</title>
<link rel="canonical" href="%s%s">
<meta http-equiv="refresh" content="0; url=%s">
<script>location.replace('%s' + location.hash);</script>
</head>
<body style="background:#0b0b0b;color:#fff;font-family:sans-serif;text-align:center;padding:60px 16px">
<p>%s results have moved. <a style="color:#e21b23" href="%s">View the results</a>.</p>
</body>
</html>
''' % (e(ev['title']), SITE, target, target, target, e(ev['title']), target)
        write('%s/index.html' % path, page)
        out.append('/%s/' % path)
    return out


def static_urls_js(D):
    events = {ev['slug']: 'events/%s/' % ev['slug'] for ev in D.static_events}
    fighters = {fid: 'fighters/%s/' % slug for fid, slug in D.fighter_slug.items()}
    js = ('/* Generated by tools/seo/build.py — links to the static event and fighter pages. */\n'
          'window.WDS_STATIC = ' + json.dumps({"events": events, "fighters": fighters}, separators=(',', ':')) + ';\n')
    write('js/wds-static-urls.js', js)


def rs8_redirect():
    p = os.path.join(ROOT, 'pages/wds-rising-star-8.html')
    s = open(p, encoding='utf-8').read()
    s = s.replace('event.html?e=wds-rising-star-8', '../events/wds-rising-star-8/')
    s = s.replace('<meta name="robots" content="noindex, follow">\n', '<link rel="canonical" href="%s/events/wds-rising-star-8/">\n' % SITE)
    open(p, 'w', encoding='utf-8').write(s)


def sitemap(event_urls, fighter_urls):
    today = dt.date.today().isoformat()
    rows = [('/', today, 'daily', '1.0'), ('/pages/events.html', today, 'daily', '0.9'),
            ('/pages/wds-fight-night-19.html', today, 'daily', '0.9'), ('/fighters/', today, 'weekly', '0.7'),
            ('/pages/about.html', today, 'monthly', '0.6'), ('/pages/media-room.html', today, 'weekly', '0.6'),
            ('/pages/contact.html', today, 'yearly', '0.5')]
    rows += [(u, d or today, 'monthly', '0.8') for u, d in event_urls]
    rows += [(u, d or today, 'monthly', '0.5') for u, d in fighter_urls]
    out = ['<?xml version="1.0" encoding="UTF-8"?>', '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for u, d, f, p in rows:
        out.append('  <url><loc>%s%s</loc><lastmod>%s</lastmod><changefreq>%s</changefreq><priority>%s</priority></url>'
                   % (SITE, u, min(d, today), f, p))
    out.append('</urlset>')
    write('sitemap.xml', '\n'.join(out) + '\n')


def mark_live_regions():
    """Mark the database-driven regions of Home and Events so prerender.js can refresh their saved copy."""
    p = os.path.join(ROOT, 'index.html')
    s = open(p, encoding='utf-8').read()
    s = mark(s, '<section class="wds-upcoming-events"', '</section>', 'home-upcoming')
    s = mark(s, '<section class="section archive-section">', '</section>', 'home-archive')
    open(p, 'w', encoding='utf-8').write(s)
    p = os.path.join(ROOT, 'pages/events.html')
    s = open(p, encoding='utf-8').read()
    if '<!--PRE:events-bands-->' not in s:
        i = s.index('<section class="event-upcoming eu-live')
        j = s.index('<section class="season-section" style', i)
        s = s[:i] + '<!--PRE:events-bands-->' + s[i:j].rstrip('\n') + '<!--/PRE:events-bands-->\n' + s[j:]
    s = mark(s, '<section class="season-section" style', '</section>', 'events-grid')
    open(p, 'w', encoding='utf-8').write(s)



def events_itemlist(D):
    """ItemList structured data on the Events page: every event page, newest first."""
    items = []
    for ev in sorted(D.events, key=lambda e: e.get('event_date') or '', reverse=True):
        if not ev.get('is_listed', True):
            continue
        if ev in D.static_events:
            url = SITE + '/events/%s/' % ev['slug']
        elif ev.get('page_url'):
            url = SITE + '/' + ev['page_url'].lstrip('/')
        else:
            continue
        items.append({"@type": "ListItem", "position": len(items) + 1, "url": url, "name": ev['title']})
    block = {"@context": "https://schema.org", "@type": "ItemList", "name": "Warriors Dream Series MMA events",
             "itemListOrder": "https://schema.org/ItemListOrderDescending", "itemListElement": items}
    p = os.path.join(ROOT, 'pages/events.html')
    s = open(p, encoding='utf-8').read()
    tag = '<script type="application/ld+json" id="wds-events-list">\n%s\n</script>\n' % json.dumps(block, ensure_ascii=False, indent=2)
    if 'id="wds-events-list"' in s:
        s = re.sub(r'<script type="application/ld\+json" id="wds-events-list">.*?</script>\n', lambda m: tag, s, count=1, flags=re.S)
    else:
        s = s.replace('</head>', tag + '</head>', 1)
    open(p, 'w', encoding='utf-8').write(s)
    return len(items)

