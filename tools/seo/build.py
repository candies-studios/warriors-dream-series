FINISH = ('KO_HEAD', 'KO_BODY', 'TKO', 'SUBMISSION', 'RNC', 'DOCTOR_STOPPAGE', 'CORNER_STOPPAGE')


def event_recap(D, ev, bouts):
    """A short written summary of a finished event plus links to the events before and after it."""
    final = [b for b in bouts if b.get('result_status') == 'final']
    pro = sum(1 for b in bouts if b.get('bout_type') == 'PROFESSIONAL')
    am = len(bouts) - pro
    finishes = sum(1 for b in final if (b.get('result_type') or '') in FINISH)
    when = fmt_date(ev.get('event_date'), long=True)
    place = ', '.join(p for p in [ev.get('venue'), ev.get('city')] if p)
    kinds = ' and '.join(x for x in ['%d professional' % pro if pro else '', '%d amateur' % am if am else ''] if x)
    text = '%s took place%s%s. The card had %d bouts (%s).' % (
        e(ev['title']), (' on ' + when) if when else '', (' at ' + e(place)) if place else '', len(bouts), kinds)
    if final:
        text += ' %d of the %d decided bouts ended inside the distance by knockout, TKO or submission.' % (finishes, len(final)) \
            if finishes else ' Every decided bout went to the judges.'
    main = bouts[-1] if bouts else None

    def link(fid, name):
        slug = D.fighter_slug.get(fid)
        return '<a href="../../fighters/%s/">%s</a>' % (slug, e(name)) if slug else e(name)
    if main and main.get('result_status') == 'final' and main.get('winner_id'):
        blue = main['winner_id'] == main['blue_fighter_id']
        win = link(main['winner_id'], main['blue_name'] if blue else main['red_name'])
        lose = link(main['red_fighter_id'] if blue else main['blue_fighter_id'], main['red_name'] if blue else main['blue_name'])
        text += ' In the main event, %s beat %s by %s.' % (win, lose, e(method(main)))
    # previous / next listed events (by date)
    seq = [x for x in D.static_events if x.get('event_date')]
    seq.sort(key=lambda x: x['event_date'])
    nav = []
    if ev in seq:
        i = seq.index(ev)
        if i > 0:
            nav.append('<a class="ev-recap-link" href="../%s/"><span>‹ Previous event</span>%s</a>' % (seq[i - 1]['slug'], e(seq[i - 1]['title'])))
        if i < len(seq) - 1:
            nav.append('<a class="ev-recap-link" href="../%s/"><span>Next event ›</span>%s</a>' % (seq[i + 1]['slug'], e(seq[i + 1]['title'])))
    nav.append('<a class="ev-recap-link" href="../../pages/events.html"><span>All events</span>WDS events &amp; results</a>')
    return ('<section class="ev-recap">\n  <div class="container ev-recap-inner">\n'
            '    <h2>%s summary</h2>\n    <p>%s</p>\n    <nav class="ev-recap-nav" aria-label="More WDS events">%s</nav>\n'
            '  </div>\n</section>\n') % (e(ev['title']), text, ''.join(nav))

def event_pages(D):
    tpl = open(os.path.join(ROOT, 'pages/event.html'), encoding='utf-8').read()
    tpl = depth_paths(tpl, 2)
    tpl = tpl.replace('<meta name="robots" content="noindex, follow">\n', '')
    tpl = mark(tpl, '<section class="page-hero', '</section>', 'hero')
    tpl = mark(tpl, '<section class="event-upcoming', '</section>', 'upcoming')
    tpl = mark(tpl, '<h2 class="season-title wds-card-title">', '</h2>', 'cardtitle')
    tpl = mark(tpl, '<div class="wds-card-list" id="wds-fight-card"', '</div>', 'card')
    tpl = tpl.replace('<body>', '<body data-event="{slug}">', 1)
    tpl = tpl.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + STATIC_FILES_NOTE + '\n', 1)
    out = []
    for ev in D.static_events:
        bouts = D.bouts_of_event(ev)
        main = bouts[-1] if bouts else None
        when = fmt_date(ev.get('event_date'), long=True)
        place = ', '.join(p for p in [ev.get('venue'), ev.get('city')] if p)
        title = '%s Results — Fight Card & Winners | WDS MMA' % ev['title']
        desc = '%s results from Warriors Dream Series: %d bouts%s%s.' % (
            ev['title'], len(bouts), (' on ' + when) if when else '', (' at ' + place) if place else '')
        if main and main.get('blue_name') and main.get('red_name'):
            desc += ' Main event: %s vs %s' % (main['blue_name'], main['red_name'])
            if main.get('result_status') == 'final' and main.get('winner_id'):
                win = main['blue_name'] if main['winner_id'] == main['blue_fighter_id'] else main['red_name']
                desc += ', won by %s by %s.' % (win, method(main))
            else:
                desc += '.'
        desc = clip(desc)
        url = '/events/%s/' % ev['slug']
        image = absolute(ev.get('poster_url')) or OG_DEFAULT
        if ev['slug'] == 'wds-rising-star-8':
            image = SITE + '/assets/images/wds-rising-star-8-hero.jpg'
        start = ev.get('event_date')
        if start and ev.get('start_time'):
            start = '%sT%s+05:30' % (start, ev['start_time'][:8])
        competitors = []
        for b in bouts:
            for fid, name in ((b['blue_fighter_id'], b['blue_name']), (b['red_fighter_id'], b['red_name'])):
                if fid and name and fid in D.fighter_slug and not any(c['name'] == name for c in competitors):
                    competitors.append({"@type": "Person", "name": name,
                                        "url": SITE + '/fighters/%s/' % D.fighter_slug[fid]})
        loc = {"@type": "Place", "name": ev.get('venue') or ev.get('city') or 'India',
               "address": {"@type": "PostalAddress", "addressLocality": ev.get('city') or ev.get('venue') or '',
                           "addressCountry": "IN"}}
        sports_event = {"@context": "https://schema.org", "@type": "SportsEvent", "name": ev['title'],
                        "sport": "Mixed Martial Arts", "description": desc, "url": SITE + url,
                        "image": [image], "startDate": start,
                        "eventStatus": "https://schema.org/EventScheduled",
                        "eventAttendanceMode": "https://schema.org/OfflineEventAttendanceMode",
                        "location": loc,
                        "organizer": {"@type": "Organization", "name": ORG, "url": SITE + "/"},
                        "competitor": competitors}
        if ev.get('end_date'):
            sports_event['endDate'] = ev['end_date']
        sports_event = {k: v for k, v in sports_event.items() if v}
        s = tpl.replace('data-event="{slug}"', 'data-event="%s"' % e(ev['slug']))
        s = set_head(s, title, desc, SITE + url, image, ld=[
            sports_event, crumbs(('Home', '/'), ('Events', '/pages/events.html'), (ev['title'], url))])
        # visible fallback before the scripts run: the event's name as the page heading
        s = s.replace('<h1>Event</h1>', '<h1>%s</h1>' % e(ev['title']), 1)
        s = s.replace('<footer class="site-footer">', event_recap(D, ev, bouts) + '<footer class="site-footer">', 1)
        write('events/%s/index.html' % ev['slug'], s)
        out.append((url, ev.get('event_date') or ''))
    return out


def fighter_pages(D):
    tpl = open(os.path.join(ROOT, 'pages/fighter.html'), encoding='utf-8').read()
    tpl = depth_paths(tpl, 2)
    tpl = tpl.replace('<meta name="robots" content="noindex, follow">\n', '')
    tpl = tpl.replace('<body>', '<body data-fighter-id="{id}">', 1)
    tpl = mark(tpl, '<main class="fp-main" id="fighterRoot">', '</main>', 'fighter')
    tpl = tpl.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + STATIC_FILES_NOTE + '\n', 1)
    out = []
    for f in D.static_fighters:
        rows = D.fights_of(f)
        pro = [r for r in rows if r['pro']]
        am = [r for r in rows if not r['pro']]
        slug = D.fighter_slug[f['id']]
        url = '/fighters/%s/' % slug
        nick = (' “%s”' % f['nickname']) if f.get('nickname') else ''
        rec = []
        if any(r['final'] for r in pro):
            rec.append('WDS pro record %s' % record(pro))
        if any(r['final'] for r in am):
            rec.append('WDS amateur record %s' % record(am))
        last = next((r for r in rows if r['final']), None)
        nxt = next((r for r in reversed(rows) if r['outcome'] == 'up'), None)
        desc = '%s%s, MMA fighter at Warriors Dream Series' % (f['name'], nick)
        if f.get('hometown'):
            desc += ' from %s' % f['hometown'].title()
        desc += (': ' + ' and '.join(rec) + '.') if rec else '.'
        if nxt:
            desc += ' Next: vs %s at %s.' % (nxt['opponent'], nxt['event']['title'])
        elif last:
            word = {'W': 'Beat', 'L': 'Lost to', 'D': 'Drew with', 'NC': 'No contest vs'}[last['outcome']]
            desc += ' %s %s at %s.' % (word, last['opponent'], last['event']['title'])
        desc = clip(desc)
        title = '%s — MMA Fighter Record & Fights | WDS MMA' % f['name']
        if len(title) > 70:
            title = '%s — MMA Record | WDS MMA' % f['name']
        image = absolute(f.get('photo_url'))
        person = {"@context": "https://schema.org", "@type": "Person", "name": f['name'],
                  "url": SITE + url, "description": desc}
        if f.get('nickname'):
            person['alternateName'] = f['nickname']
        if image:
            person['image'] = image
        if f.get('country'):
            person['nationality'] = {"@type": "Country", "name": f['country']}
        if f.get('hometown'):
            person['homeLocation'] = {"@type": "Place", "name": f['hometown'].title()}
        s = tpl.replace('data-fighter-id="{id}"', 'data-fighter-id="%s"' % e(f['id']))
        s = set_head(s, title, desc, SITE + url, image or OG_DEFAULT, og_type='profile', ld=[
            person, crumbs(('Home', '/'), ('Fighters', '/fighters/'), (f['name'], url))])
        write('fighters/%s/index.html' % slug, s)
        out.append((url, rows[0]['date'] if rows else ''))
    return out


